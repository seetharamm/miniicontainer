'use strict';
/**
 * DNS configuration for containers.
 *
 * Linux:
 *   Writes /etc/resolv.conf into the rootfs with:
 *   - Host's own nameservers (from /etc/resolv.conf) so the container
 *     inherits the host's DNS — works on corporate networks with split-DNS.
 *   - Falls back to Google (8.8.8.8 / 8.8.4.4) and Cloudflare (1.1.1.1)
 *     if the host has no resolv.conf or it only contains loopback addresses
 *     (systemd-resolved on Ubuntu writes 127.0.0.53 which is unreachable
 *     inside the container netns).
 *   - Appends "options ndots:5 timeout:2 attempts:3" for reliability.
 *
 * Windows:
 *   Container processes share the host network stack, so DNS works
 *   automatically.  This module writes a resolv.conf-style file anyway
 *   so that Linux tools compiled for Windows (WSL interop, git-bash, etc.)
 *   can find nameservers.
 *   Also optionally starts a lightweight UDP DNS proxy on 172.30.0.1:53
 *   so containers on the minicontainer bridge can resolve names.
 */

const path = require('path');
const fs   = require('fs-extra');
const os   = require('os');

const PUBLIC_DNS = ['8.8.8.8', '8.8.4.4', '1.1.1.1'];
const LOOPBACK   = /^127\.|^::1$/;

// ── Linux ────────────────────────────────────────────────────────────────────

/**
 * Write a working /etc/resolv.conf into the container rootfs.
 *
 * @param {string} rootfs       Path to the container's root filesystem
 * @param {string[]} [extraNS]  Additional nameservers to prepend
 */
async function configureResolvConf(rootfs, extraNS = []) {
  const etcDir     = path.join(rootfs, 'etc');
  const resolvPath = path.join(etcDir, 'resolv.conf');
  await fs.ensureDir(etcDir);

  const nameservers = [
    ...extraNS,
    ...readHostNameservers(),
    ...PUBLIC_DNS,
  ];

  // De-duplicate, keep at most 3 (resolv.conf limit)
  const seen   = new Set();
  const unique = nameservers.filter(ip => {
    if (seen.has(ip)) return false;
    seen.add(ip);
    return true;
  }).slice(0, 3);

  const content = [
    '# Generated by minicontainer',
    ...unique.map(ip => `nameserver ${ip}`),
    'search .',
    'options ndots:5 timeout:2 attempts:3',
    '',
  ].join('\n');

  await fs.writeFile(resolvPath, content, 'utf8');
  return unique;
}

/**
 * Read nameservers from the host's /etc/resolv.conf.
 * Filters out loopback addresses (127.x.x.x, ::1) that are unreachable
 * inside an isolated network namespace.
 */
function readHostNameservers() {
  const hostResolv = '/etc/resolv.conf';
  if (!fs.existsSync(hostResolv)) return [];

  try {
    return fs
      .readFileSync(hostResolv, 'utf8')
      .split('\n')
      .filter(l => l.startsWith('nameserver'))
      .map(l => l.split(/\s+/)[1])
      .filter(ip => ip && !LOOPBACK.test(ip));
  } catch {
    return [];
  }
}

// ── Windows ──────────────────────────────────────────────────────────────────

/**
 * On Windows: write a resolv.conf-style file with the host's DNS servers.
 * The container shares the host network stack so DNS already works,
 * but this file helps tools that read resolv.conf (git-bash, WSL tools).
 */
async function configureWindowsDns(rootfs) {
  const etcDir     = path.join(rootfs, 'etc');
  const resolvPath = path.join(etcDir, 'resolv.conf');
  await fs.ensureDir(etcDir);

  // On Windows, try to read DNS from ipconfig /all via getHostDnsWindows()
  const nameservers = [...(await getHostDnsWindows()), ...PUBLIC_DNS]
    .filter((ip, i, arr) => arr.indexOf(ip) === i)
    .slice(0, 3);

  const content = [
    '# Generated by minicontainer (Windows)',
    ...nameservers.map(ip => `nameserver ${ip}`),
    '',
  ].join('\n');

  await fs.writeFile(resolvPath, content, 'utf8').catch(() => {});
  return nameservers;
}

/**
 * Parse DNS server IPs from `ipconfig /all` on Windows.
 */
async function getHostDnsWindows() {
  try {
    const { run } = require('../utils/exec');
    const { stdout } = await run('ipconfig', ['/all']);
    const matches = stdout.match(/DNS Servers[^\n]*:\s*([\d.]+)/gi) || [];
    return matches
      .map(m => m.replace(/.*:\s*/, '').trim())
      .filter(ip => ip && !LOOPBACK.test(ip));
  } catch {
    return [];
  }
}

// ── /etc/hosts ───────────────────────────────────────────────────────────────

/**
 * Write a minimal /etc/hosts into the container rootfs.
 *
 * @param {string} rootfs
 * @param {string} containerIp   The container's own IP (for hostname resolution)
 * @param {string} hostname      The container's hostname
 * @param {string} gatewayIp     The bridge gateway IP
 */
async function configureHosts(rootfs, containerIp, hostname, gatewayIp) {
  const hostsPath = path.join(rootfs, 'etc', 'hosts');
  await fs.ensureDir(path.join(rootfs, 'etc'));

  const content = [
    '127.0.0.1   localhost',
    '::1         localhost ip6-localhost ip6-loopback',
    `${containerIp}   ${hostname}`,
    `${gatewayIp}     host.minicontainer.internal`,
    '',
  ].join('\n');

  await fs.writeFile(hostsPath, content, 'utf8');
}

/**
 * Write /etc/hostname into the container rootfs.
 */
async function configureHostname(rootfs, hostname) {
  await fs.ensureDir(path.join(rootfs, 'etc'));
  await fs.writeFile(path.join(rootfs, 'etc', 'hostname'), hostname + '\n', 'utf8');
}

module.exports = {
  configureResolvConf,
  configureHosts,
  configureHostname,
  configureWindowsDns,
  readHostNameservers,
};
